import { test, expect } from '@playwright/test'

test('play, pause, seek, change speed, close and reopen original and archived video', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('button', { name: '录像文件', exact: true }).click()

  const original = page.getByRole('button', { name: '播放 day/00_20251008080000_20251008080100.mp4', exact: true })
  const card = page.getByRole('article', { name: 'day/00_20251008080000_20251008080100.mp4', exact: true })
  await expect(card.locator('img')).toBeVisible()
  await expect.poll(() => card.locator('img').evaluate(element => (element as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await expect(card.getByText('测试摄像机 · 编号 00')).toBeVisible()
  await expect(card.getByText('录像时长', { exact: true })).toBeVisible()
  await page.screenshot({ path: '/tmp/cammon-thumbnail-list.png', fullPage: true })
  const responsePromise = page.waitForResponse(response => response.url().endsWith('/stream') && response.request().method() === 'GET')
  await original.click()
  const response = await responsePromise
  expect(response.status()).toBe(206)
  expect(response.headers()['content-disposition']).toMatch(/^inline;/)
  const dialog = page.getByRole('dialog', { name: '在线播放', exact: true })
  const video = dialog.locator('video')
  await expect(dialog).toBeVisible()
  await expect.poll(() => video.evaluate(element => element.readyState)).toBeGreaterThanOrEqual(2)
  expect(await video.evaluate(element => element.duration)).toBeCloseTo(60, 0)
  await video.evaluate(async element => { await element.play() })
  await expect.poll(() => video.evaluate(element => element.currentTime)).toBeGreaterThan(0)
  await video.evaluate(element => element.pause())
  expect(await video.evaluate(element => element.paused)).toBeTruthy()
  await video.evaluate(element => { element.currentTime = 35 })
  await expect.poll(() => video.evaluate(element => !element.seeking && element.currentTime >= 35)).toBeTruthy()
  await dialog.getByLabel('播放速度').selectOption('2')
  expect(await video.evaluate(element => element.playbackRate)).toBe(2)
  expect(await video.evaluate(element => element.controls && element.playsInline)).toBeTruthy()
  await page.screenshot({ path: '/tmp/cammon-playback.png', fullPage: true })

  // Retain the DOM handle to verify that closing also stops the detached media element.
  const detachedVideo = await video.elementHandle()
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  expect(await detachedVideo!.evaluate(element => element.paused && !element.hasAttribute('src'))).toBeTruthy()
  await original.click()
  await expect.poll(() => video.evaluate(element => element.readyState)).toBeGreaterThanOrEqual(2)
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)

  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: '/tmp/cammon-thumbnail-list-mobile.png', fullPage: true })
  await page.getByRole('button', { name: '播放 00_2025-10-08_archive.mp4', exact: true }).click()
  await expect.poll(() => video.evaluate(element => element.readyState)).toBeGreaterThanOrEqual(2)
  await expect(dialog.getByText('归档已按原录像时间压缩 60 倍', { exact: false })).toBeVisible()
  expect(await video.evaluate(element => element.duration)).toBeLessThan(2)
  expect(await video.evaluate(element => element.playbackRate)).toBe(1)
  const bounds = await dialog.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
  const downloadPromise = page.waitForEvent('download')
  await dialog.getByRole('link', { name: '下载录像', exact: true }).click()
  expect(await (await downloadPromise).failure()).toBeNull()
  await page.screenshot({ path: '/tmp/cammon-playback-mobile.png', fullPage: true })
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()

  await expect(page.getByRole('button', { name: '播放 day/99_20251008080000_20251008080100.mp4', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '播放 day/98_20251008080000_20251008080100.mp4', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('无法播放此录像')
  await dialog.getByRole('button', { name: '重新加载' }).click()
  await expect(dialog.getByRole('alert')).toContainText('无法播放此录像')
  await expect(dialog.getByRole('link', { name: '下载录像', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
