import { test, expect } from './fixtures'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

test('login, devices, conjunctive filters, download, settings and mobile layout', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '存储总览', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '摄像机管理', exact: true }).click()
  await page.getByRole('button', { name: '添加摄像机', exact: true }).click()
  await page.getByLabel('设备名称').fill('后院摄像机')
  await page.getByLabel('原录像保留天数').fill('14')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('heading', { name: '摄像机接入信息' })).toBeVisible()
  await page.getByRole('button', { name: '已保存接入信息' }).click()
  await expect(page.getByRole('heading', { name: '后院摄像机', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '录像文件', exact: true }).click()
  await page.getByLabel('相机编号 X').fill('00')
  await page.getByLabel('指定日期').fill('2025-10-08')
  await page.getByLabel('年份').fill('2025')
  await page.getByLabel('月份').selectOption('10')
  await page.getByLabel('视频类型').selectOption('original')
  const row = page.getByRole('article', { name: 'day/00_20251008080000_20251008080100.mp4', exact: true })
  await expect(row).toBeVisible()
  const pending = page.waitForEvent('download')
  await row.getByRole('link').click()
  const download = await pending
  expect(await download.failure()).toBeNull()
  await page.getByLabel('相机编号 X').fill('0')
  await expect(page.getByText('没有符合条件的录像')).toBeVisible()
  await page.getByLabel('相机编号 X').fill('00')
  await expect(row).toBeVisible()
  await page.screenshot({ path: '/tmp/cammon-files.png', fullPage: true })
  await page.getByRole('button', { name: '真实存储', exact: true }).click()
  await expect(page.getByRole('heading', { name: '元数据数据库' })).toBeVisible()
  await expect(page.getByText('尚未配置 · 仅内存运行')).toBeVisible()
  const localButton = page.getByRole('button', { name: /本地磁盘/ })
  await expect(localButton).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByLabel('磁盘路径')).toHaveValue('/data')
  await expect(page.getByLabel('NFS 版本')).toHaveCount(0)
  await expect(page.getByLabel('密码', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: /NFS/ }).click()
  await expect(page.getByLabel('NFS 版本')).toBeVisible()
  await page.getByRole('button', { name: /SMB2/ }).click()
  await expect(page.getByLabel('用户名', { exact: true })).toBeVisible()
  await expect(page.getByLabel('密码', { exact: true })).toBeVisible()
  await localButton.click()
  await expect(page.getByLabel('磁盘路径')).toHaveValue('/data')
  const localDisk = mkdtempSync(join(tmpdir(), 'cammon-browser-storage-'))
  try {
    await page.getByLabel('磁盘路径').fill(localDisk)
    await page.getByRole('button', { name: '测试读写连接' }).click()
    await expect(page.getByRole('status')).toContainText('连接、写入、读取、改名和删除均成功')
    await page.getByRole('button', { name: '保存配置' }).click()
    await expect(page.getByRole('status')).toContainText('存储设置已保存')
    await page.reload()
    await page.getByRole('button', { name: '真实存储', exact: true }).click()
    await expect(localButton).toHaveAttribute('aria-pressed', 'true')
    await expect(page.getByLabel('磁盘路径')).toHaveValue(localDisk)
    const history = join(localDisk, '旧录像')
    mkdirSync(join(history, '嵌套', '目录'), { recursive: true })
    writeFileSync(join(history, '02_20251008080000_20251008080100.mp4'), 'import-download-fixture')
    writeFileSync(join(history, '嵌套', '目录', '03_20251009080000_20251009080100.mp4'), 'nested-fixture')
    writeFileSync(join(history, 'notes.txt'), 'ignore this file')
    await page.getByRole('button', { name: '旧录像导入', exact: true }).click()
    await page.getByRole('button', { name: '浏览文件夹' }).click()
    await page.getByRole('button', { name: '旧录像', exact: true }).click()
    await page.getByRole('button', { name: '选择此文件夹' }).click()
    await expect(page.getByLabel('导入文件夹')).toHaveValue(history)
    await page.getByLabel('归属摄像机').selectOption({ label: '后院摄像机 · 保留 14 天' })
    await page.getByRole('button', { name: '预览导入' }).click()
    await expect(page.getByText(/共 3 个文件 · 可导入 2 个/)).toBeVisible()
    await page.getByRole('button', { name: '开始导入' }).click()
    await expect(page.getByRole('heading', { name: '导入结果' })).toBeVisible()
    await expect(page.getByText(/共 3 个文件 · 已导入 2 个/)).toBeVisible()
    await page.getByRole('button', { name: '录像文件', exact: true }).click()
    await page.getByRole('button', { name: '旧录像导入', exact: true }).click()
    await expect(page.getByText(/共 3 个文件 · 已导入 2 个/)).toBeVisible()
    await page.reload()
    await page.getByRole('button', { name: '旧录像导入', exact: true }).click()
    await expect(page.getByText(/共 3 个文件 · 已导入 2 个/)).toBeVisible()
    await expect(page.getByLabel('导入文件夹')).toHaveValue(history)
    await page.getByRole('button', { name: '预览导入' }).click()
    await expect(page.getByText(/共 3 个文件 · 可导入 0 个/)).toBeVisible()
    await expect(page.getByRole('button', { name: '开始导入' })).toBeDisabled()
    const duplicates = join(localDisk, '重复录像')
    mkdirSync(duplicates)
    writeFileSync(join(duplicates, '02_20251008080000_20251008080100.mp4'), 'import-download-fixture')
    await page.getByLabel('导入文件夹').fill(duplicates)
    await page.getByRole('button', { name: '预览导入' }).click()
    await expect(page.getByText(/共 1 个文件 · 可导入 0 个/)).toBeVisible()
    await expect(page.getByText('可关联副本 1 个 · 归档成功后清理')).toBeVisible()
    await expect(page.getByRole('button', { name: '开始导入' })).toBeEnabled()
    await page.getByRole('button', { name: '开始导入' }).click()
    await expect(page.getByText('已关联副本 1 个 · 归档成功后清理')).toBeVisible()
    await page.getByRole('button', { name: '预览导入' }).click()
    await expect(page.getByRole('button', { name: '开始导入' })).toBeDisabled()
    await page.setViewportSize({ width: 390, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
    await page.screenshot({ path: '/tmp/cammon-import.png', fullPage: true })
    await page.getByRole('button', { name: '录像文件', exact: true }).click()
    await page.getByRole('button', { name: '重置', exact: true }).click()
    await page.getByLabel('相机编号 X').fill('02')
    const imported = page.getByRole('article').filter({ hasText: '02_20251008080000_20251008080100.mp4' })
    await expect(imported).toBeVisible()
    const importedDownload = page.waitForEvent('download')
    await imported.getByRole('link').click()
    expect(await (await importedDownload).failure()).toBeNull()
  } finally {
    rmSync(localDisk, { recursive: true, force: true })
  }
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: '/tmp/cammon-mobile.png', fullPage: true })
  expect(errors).toEqual([])
})
